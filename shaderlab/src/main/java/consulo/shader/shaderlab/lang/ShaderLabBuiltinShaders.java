    private static final Set<String> ourLowerCaseNames = buildLowerCaseNames();

    private ShaderLabBuiltinShaders()
    {
    }

    /**
     * @param name unquoted shader name, compared case-insensitively like Unity does
     */
    public static boolean isBuiltin(String name)
    {
        return ourLowerCaseNames.contains(name.toLowerCase(Locale.ROOT));
    }

    private static Set<String> buildLowerCaseNames()
    {
        Set<String> result = new TreeSet<>();
        for (String name : NAMES)
        {
            result.add(name.toLowerCase(Locale.ROOT));
        }
        for (String name : LEGACY_ALIASES)
        {
            result.add(name.toLowerCase(Locale.ROOT));
        }
        return result;
    }
